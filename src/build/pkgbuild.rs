//! Generates the PKGBUILD for the makepkg backend.

use std::fmt::Write as _;

use crate::model::{NodeKind, Package};

/// The tree Ferry prepared, next to the PKGBUILD.
pub const TREE_DIR: &str = "pkgroot";

/// `origin` names the deb, for the header comment.
pub fn render(pkg: &Package, origin: &str) -> String {
    let mut s = String::new();
    let v = &pkg.version;
    writeln!(s, "# Generated by Ferry from {}. Ferry rewrites this file on every build.", one_line(origin)).unwrap();
    writeln!(s, "pkgname={}", quote(&pkg.name)).unwrap();
    writeln!(s, "pkgver={}", quote(&v.pkgver)).unwrap();
    writeln!(s, "pkgrel={}", v.pkgrel).unwrap();
    if v.epoch > 0 {
        writeln!(s, "epoch={}", v.epoch).unwrap();
    }
    writeln!(s, "pkgdesc={}", quote(&one_line(&pkg.description))).unwrap();
    writeln!(s, "arch=({})", quote(&pkg.arch)).unwrap();
    if let Some(url) = &pkg.url {
        writeln!(s, "url={}", quote(url)).unwrap();
    }
    writeln!(s, "license=({})", quote(&pkg.license)).unwrap();
    array(&mut s, "depends", pkg.depends.iter().cloned());
    array(&mut s, "optdepends", pkg.optdepends.iter().map(|(p, why)| format!("{p}: {why}")));
    array(&mut s, "provides", pkg.provides.iter().cloned());
    array(&mut s, "conflicts", pkg.conflicts.iter().cloned());
    array(&mut s, "backup", pkg.backup.iter().cloned());
    // Prebuilt binaries (Electron ones especially) can break when stripped, and there
    // is nothing to build debug info for.
    writeln!(s, "options=('!strip' '!debug')").unwrap();
    if !pkg.install_note.is_empty() {
        writeln!(s, "install={}", quote(&install_file_name(pkg))).unwrap();
    }
    s.push('\n');
    s.push_str("package() {\n");
    s.push_str("  # Ferry already laid out every file; copy the tree in unchanged. Running under\n");
    s.push_str("  # fakeroot makes all of it owned by root.\n");
    writeln!(s, "  cp -a --reflink=auto \"$startdir/{TREE_DIR}/.\" \"$pkgdir/\"").unwrap();
    // Spelled out so the special modes are visible in the PKGBUILD itself.
    for n in pkg.nodes.iter().filter(|n| n.kind == NodeKind::File && n.mode & 0o7000 != 0) {
        writeln!(s, "  chmod {:04o} \"$pkgdir\"{}", n.mode, quote(&n.path)).unwrap();
    }
    s.push_str("}\n");
    s
}

pub fn install_file_name(pkg: &Package) -> String {
    format!("{}.install", pkg.name)
}

/// The .install scriptlet: it only prints the note after a fresh install. Ferry never
/// puts commands from the deb's scripts in here.
pub fn install_script(pkg: &Package) -> Option<String> {
    if pkg.install_note.is_empty() {
        return None;
    }
    let mut s = String::from("post_install() {\n  cat <<'FERRY_NOTE'\n");
    for line in &pkg.install_note {
        s.push_str(line);
        s.push('\n');
    }
    s.push_str("FERRY_NOTE\n}\n");
    Some(s)
}

fn array(s: &mut String, name: &str, items: impl Iterator<Item = String>) {
    let items: Vec<String> = items.map(|i| quote(&i)).collect();
    if items.is_empty() {
        return;
    }
    if items.len() <= 3 {
        writeln!(s, "{name}=({})", items.join(" ")).unwrap();
        return;
    }
    writeln!(s, "{name}=(").unwrap();
    for i in items {
        writeln!(s, "  {i}").unwrap();
    }
    s.push_str(")\n");
}

/// Single quotes for bash, with embedded quotes escaped.
fn quote(v: &str) -> String {
    format!("'{}'", v.replace('\'', "'\\''"))
}

fn one_line(v: &str) -> String {
    v.split_whitespace().collect::<Vec<_>>().join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Node, Source};
    use crate::version::{ArchVersion, DebVersion};

    fn package() -> Package {
        let deb_version = DebVersion::parse("2:1.0~rc1-3").unwrap();
        Package {
            name: "demo".into(),
            version: ArchVersion::from_debian(&deb_version, 2),
            deb_version,
            arch: "x86_64".into(),
            description: "Demo's app\n  with spaces".into(),
            url: Some("https://example.com".into()),
            license: "custom".into(),
            depends: vec!["gtk3".into(), "nss".into(), "alsa-lib".into(), "libsecret".into()],
            optdepends: vec![("libpulse".into(), "recommended by the deb".into())],
            provides: vec!["demo-app".into()],
            conflicts: vec!["demo-bin".into()],
            backup: vec!["etc/default/demo".into()],
            install_note: vec![],
            nodes: vec![
                Node { path: "/opt/Demo/chrome-sandbox".into(), kind: NodeKind::File, mode: 0o4755, size: 1, source: Source::None },
                Node { path: "/opt/Demo/demo".into(), kind: NodeKind::File, mode: 0o755, size: 1, source: Source::None },
            ],
        }
    }

    #[test]
    fn renders() {
        let got = render(&package(), "demo_1.0_amd64.deb");
        let want = "\
# Generated by Ferry from demo_1.0_amd64.deb. Ferry rewrites this file on every build.
pkgname='demo'
pkgver='1.0~rc1'
pkgrel=2
epoch=2
pkgdesc='Demo'\\''s app with spaces'
arch=('x86_64')
url='https://example.com'
license=('custom')
depends=(
  'gtk3'
  'nss'
  'alsa-lib'
  'libsecret'
)
optdepends=('libpulse: recommended by the deb')
provides=('demo-app')
conflicts=('demo-bin')
backup=('etc/default/demo')
options=('!strip' '!debug')

package() {
  # Ferry already laid out every file; copy the tree in unchanged. Running under
  # fakeroot makes all of it owned by root.
  cp -a --reflink=auto \"$startdir/pkgroot/.\" \"$pkgdir/\"
  chmod 4755 \"$pkgdir\"'/opt/Demo/chrome-sandbox'
}
";
        assert_eq!(got, want);
    }

    #[test]
    fn leaves_out_empty_fields() {
        let mut p = package();
        p.version = ArchVersion { epoch: 0, pkgver: "1.0".into(), pkgrel: 1 };
        p.url = None;
        p.optdepends.clear();
        p.provides.clear();
        p.conflicts.clear();
        p.backup.clear();
        let got = render(&p, "x.deb");
        for absent in ["epoch=", "url=", "optdepends=", "provides=", "conflicts=", "backup=", "install="] {
            assert!(!got.contains(absent), "{absent} in:\n{got}");
        }
        assert_eq!(install_script(&p), None);
    }

    #[test]
    fn writes_an_install_note() {
        let mut p = package();
        p.install_note = vec!["To start it:".into(), "  sudo systemctl enable --now demo.service".into()];
        assert!(render(&p, "x.deb").contains("install='demo.install'\n"));
        assert_eq!(
            install_script(&p).unwrap(),
            "post_install() {\n  cat <<'FERRY_NOTE'\nTo start it:\n  sudo systemctl enable --now demo.service\nFERRY_NOTE\n}\n"
        );
    }
}
